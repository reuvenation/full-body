// Service worker для FullBody — офлайн-оболочка приложения.
// Кэшируем только СВОИ статические файлы (same-origin GET).
// Запросы к Supabase и сторонним API (другой origin) НЕ трогаем — данные и
// авторизация всегда идут по сети и остаются свежими.
//
// ⚠️ ГЛАВНОЕ ПРАВИЛО ЭТОГО ФАЙЛА (жалоба владельца 28.08.2026, разбор ниже):
// ЗАДУШЕННАЯ сеть для нас опаснее оборванной. При обрыве fetch падает мгновенно,
// срабатывает фолбэк и приложение работает офлайн. А при DPI-душении запрос НЕ
// падает — он висит (замер 28.08: TLS-рукопожатие к одному адресу 0,11 / 1,50 /
// 4,84 с при мгновенном TCP). Прежняя версия ждала такой fetch без ограничения
// по времени, и человек видел белый экран с полоской загрузки: интерфейс не
// появлялся ВООБЩЕ, хотя в кэше лежало 30 готовых файлов.
// Поэтому у каждого ожидания сети здесь обязан быть потолок, если есть что
// показать из кэша. Не убирать Promise.race — он тут не оптимизация, а лечение.
//
// ⚠️ Версию кэша поднимать при смене стратегии: старый кэш вычищается в activate.
// v1 (по май 2026) не менялся никогда, поэтому у людей копились старые index.html
// и бандлы — вторая половина той же жалобы, «сайт показывает старую версию».
const CACHE = 'fullbody-v2'

// ⛔️ ПРЕДКЭША ОБОЛОЧКИ БОЛЬШЕ НЕТ. Утром 28.08 здесь появился `SHELL = ['./','./index.html']`
// — «чтобы фолбэк был с первого захода». Идея оказалась вредной, и дорого:
// в кэш ложилась СТРАНИЦА БЕЗ АССЕТОВ (их имена на момент установки неизвестны).
// Толку от такой страницы ноль — она всё равно не откроется без своего бандла, —
// а вреда много: после следующего деплоя `deploy.sh` затирает ветку целиком, старый
// `assets/index-*.js` отдаёт 404, и человек получает БЕЛЫЙ ЭКРАН на каждом заходе,
// потому что кэш цел и обновляться ему незачем. Так владелец просидел полдня.
// Кэш наполняется сам при первом удачном заходе — страницей И её ассетами разом,
// то есть комплектом, который реально работает.

// Сколько ждём сеть при переходе на страницу, ЕСЛИ есть что показать из кэша.
// 1,2 с: живой ответ укладывается (замер прода — 0,3…0,8 с), а задушенный
// не тормозит запуск. Когда кэша нет, ждём сколько потребуется — выбора нет.
const NAV_TIMEOUT = 1200

self.addEventListener('install', () => {
  self.skipWaiting()
})

self.addEventListener('activate', (event) => {
  event.waitUntil(
    (async () => {
      // ⛔️ СТАРЫЙ КЭШ ПЕРЕНОСИМ, А НЕ ВЫБРАСЫВАЕМ. Ошибка 28.08, замеченная сразу
      // после выката: `caches.delete` по всем чужим ключам ОТБИРАЛ у человека
      // офлайн-запас ровно в тот момент, когда сеть душат, — а наполнить новый кэш
      // нечем, он берётся только из удачных ответов сети. У владельца после смены
      // версии сайт перестал открываться совсем: раньше поднимался из кэша `v1`
      // «через несколько минут», а стало неоткуда.
      // Старый index.html как фолбэк — не идеал, но рабочая старая версия несравнимо
      // лучше белого экрана, а свежая догоняется фоновым обновлением.
      const fresh = await caches.open(CACHE)
      for (const key of await caches.keys()) {
        if (key === CACHE) continue
        const old = await caches.open(key)
        for (const req of await old.keys()) {
          if (await fresh.match(req)) continue
          const res = await old.match(req)
          if (res) await fresh.put(req, res)
        }
        await caches.delete(key)
      }
      await self.clients.claim()
    })()
  )
})

self.addEventListener('fetch', (event) => {
  const req = event.request
  if (req.method !== 'GET') return
  const url = new URL(req.url)
  // только наш origin; чужие (Supabase, Метрика) — мимо, пусть идут по сети.
  // Шрифты с 12.08.2026 лежат у нас же (public/fonts) и кэшируются как обычная статика.
  if (url.origin !== self.location.origin) return
  // сам SW через кэш не отдаём — иначе исправление этого файла не доедет до людей
  if (url.pathname.endsWith('/sw.js')) return

  // ── навигация: сеть с потолком ожидания, фолбэк — кэш ──
  if (req.mode === 'navigate') {
    event.respondWith(
      (async () => {
        const cache = await caches.open(CACHE)
        const cached = (await cache.match(req)) || (await cache.match('./index.html'))
        const network = fetch(req).then((res) => {
          if (res && res.status === 200) cache.put(req, res.clone())
          return res
        })

        // Показать нечего — ждём сеть до победного.
        if (!cached) {
          return network.catch(
            () => new Response('Нет связи с сервером. Откройте страницу ещё раз.', {
              status: 503,
              headers: { 'Content-Type': 'text/plain; charset=utf-8' },
            })
          )
        }

        // Кэш есть: даём сети фору, потом поднимаем оболочку из кэша, а запрос
        // пусть доедет в фоне и обновит кэш — тогда СЛЕДУЮЩИЙ заход будет свежим.
        // waitUntil обязателен: без него браузер вправе усыпить SW сразу после
        // ответа, и фоновое обновление не дописалось бы никогда.
        event.waitUntil(network.catch(() => {}))
        return Promise.race([
          network.catch(() => cached),
          new Promise((resolve) => setTimeout(() => resolve(cached), NAV_TIMEOUT)),
        ])
      })()
    )
    return
  }

  // ── статика: stale-while-revalidate ──
  event.respondWith(
    (async () => {
      const cache = await caches.open(CACHE)
      const cached = await cache.match(req)
      const network = fetch(req).then((res) => {
        if (res && res.status === 200) cache.put(req, res.clone())
        return res
      })
      if (cached) {
        event.waitUntil(network.catch(() => {}))
        return cached
      }
      // В кэше нет (после деплоя у бандлов новые имена) — взять больше неоткуда.
      // ⚠️ Прежняя версия на этом месте возвращала undefined при сбое сети,
      // и браузер показывал невнятную ошибку вместо честного статуса.
      const res = await network.catch(() => new Response('', { status: 504 }))

      // ⛔️ 404 на своём же ассете = мы отдали ПРОТУХШИЙ index.html.
      // Механизм (поймали 28.08 на живом телефоне владельца): `deploy.sh` пушит ветку
      // целиком, поэтому после деплоя старые `assets/index-*.js` физически ИСЧЕЗАЮТ.
      // Кэшированная страница ссылается на такой файл — он отдаёт 404, приложение
      // не стартует, человек видит белый экран, и так при КАЖДОМ заходе: кэш-то цел.
      // Лечение — выбросить сохранённые навигации, чтобы следующий заход пошёл в сеть
      // за свежей страницей. Сам ассет уже не спасти, но ловушка размыкается.
      if (res.status === 404 && url.pathname.includes('/assets/')) {
        for (const req of await cache.keys()) {
          if (req.mode === 'navigate' || /\/(index\.html)?$/.test(new URL(req.url).pathname)) {
            await cache.delete(req)
          }
        }
      }
      return res
    })()
  )
})
